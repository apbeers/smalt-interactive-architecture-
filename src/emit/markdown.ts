// The model as Markdown, for agents: llms.txt, one platform overview, one page per repository and one per file.
// Every page names node ids, so an agent can go from a page to data/repo/<name>.json or to `bin/arch.mjs show <id>`.
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import type { Model } from '../analyze/graph.js';
import type { Changes } from './data.js';
import type { FileNode, Issue, RepoNode } from '../model.js';

const write = (path: string, text: string): void => {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, text);
};

export const mdPath = {
  repo: (repo: string): string => `md/${repo}.md`,
  file: (file: FileNode): string => `md/${file.repo}/${file.path}.md`,
};

const code = (s: string): string => '`' + s.replace(/`/g, "'") + '`';
const firstLine = (s: string | undefined): string => (s ?? '').split('\n')[0]!.trim();
const blob = (repo: RepoNode, path: string, line?: number): string => `${repo.url}/blob/${repo.commit}/${path}${line ? `#L${line}` : ''}`;

function issueLines(issues: Issue[]): string[] {
  const order = { error: 0, warning: 1, info: 2 };
  return [...issues].sort((a, b) => order[a.severity] - order[b.severity]).map((i) => {
    const ev = i.evidence?.[0];
    const where = ev ? ` (${ev.at}${ev.line ? `:${ev.line}` : ''})` : '';
    return `- **${i.severity}** \`${i.rule}\` ${i.node}: ${i.message}${where}${i.fix ? ` Fix: ${i.fix}` : ''}`;
  });
}

export function writeMarkdown(model: Model, issues: Issue[], changes: Changes, out: string): void {
  const site = model.config.siteUrl;
  const byNode = new Map<string, Issue[]>();
  for (const i of issues) (byNode.get(i.node) ?? byNode.set(i.node, []).get(i.node)!).push(i);
  const issuesInRepo = (repo: string): Issue[] => issues.filter((i) => i.node === repo || i.node.startsWith(repo + '/') || model.entries.get(i.node)?.repo === repo);
  const layers = model.config.layers;
  const counts = { error: 0, warning: 0, info: 0 } as Record<string, number>;
  for (const i of issues) counts[i.severity]!++;

  // llms.txt
  write(join(out, 'llms.txt'), [
    `# ${model.config.title}`,
    '',
    `> The smalt family's repositories (${model.config.owner}/*, main branches) as one architecture: products, entry points, files, exported symbols, how they depend on each other, and what is wrong. Generated by a static analyzer (smaltty's parser), not by a model; regenerated on every run.`,
    '',
    'Start with the platform overview, then the page of the repository you are working in. Before changing an export, look up who uses it.',
    '',
    '## Context',
    '',
    `- [Platform overview](${site}context/platform.md): every repository, its layer, entry points and dependencies, and every error and warning`,
    ...model.repos.filter((r) => r.stats.files > 0).map((r) => `- [${r.name}](${site}${mdPath.repo(r.name)}): ${r.whatItIs ?? r.description ?? ''}`),
    '',
    '## Data',
    '',
    `- [data/index.json](${site}data/index.json): repositories, entry points with their API, repository edges, issues, rules (schema: src/model.ts, IndexData)`,
    `- data/repo/<name>.json: one repository's directories, files, symbols and file-level edges (RepoData)`,
    `- [data/search.json](${site}data/search.json): [id, name, kind, repo, detail] for every node`,
    `- [data/changes.json](${site}data/changes.json): what changed since the previous build (API, edges, commits)`,
    `- md/<repo>/<path>.md: one page per source file: imports, importers, symbols with signatures and users`,
    '',
    '## Optional',
    '',
    `- Query tool: \`node bin/arch.mjs help\` in the architecture repository (who-uses, impact, find, show, issues, rules)`,
    `- [For agents](${site}md/AGENTS.md): how to use this before and after a change`,
    '',
  ].join('\n'));

  // context/platform.md
  const lines: string[] = [
    `# ${model.config.title}`,
    '',
    `Generated ${changes.to} from ${model.config.owner}/* main branches. Issues: ${counts.error} errors, ${counts.warning} warnings, ${counts.info} info. Interactive: ${site}`,
    '',
    '## Layers and repositories',
    '',
  ];
  for (const layer of layers) {
    const repos = model.repos.filter((r) => r.layer === layer.id);
    if (!repos.length) continue;
    lines.push(`### ${layer.name}`, '', layer.about, '');
    for (const r of repos) {
      const entries = [...model.entries.values()].filter((e) => e.repo === r.name);
      const deps = [...new Set(r.dependencies.filter((d) => d.repo && d.repo !== r.name && !d.dev).map((d) => d.repo))];
      lines.push(`- **${r.name}**${r.packageName && r.packageName !== r.name ? ` (${code(r.packageName)})` : ''}: ${r.intent?.summary ?? r.whatItIs ?? r.description ?? r.readme ?? 'No description.'} ${r.stats.files} files, ${r.stats.loc} lines.`);
      if (entries.length) lines.push(`  Entry points: ${entries.map((e) => `${code(e.name)} (${e.api.length})`).join(', ')}.`);
      if (deps.length) lines.push(`  Depends on: ${deps.join(', ')}.`);
      lines.push(`  Details: ${site}${mdPath.repo(r.name)}`);
    }
    lines.push('');
  }
  lines.push('## Dependencies between repositories', '', '| From | To | Kind | Weight | Evidence |', '| --- | --- | --- | --- | --- |');
  for (const e of [...model.repoEdges].sort((a, b) => a.from.localeCompare(b.from) || a.to.localeCompare(b.to))) {
    lines.push(`| ${e.from} | ${e.to} | ${e.kind} | ${e.weight} | ${(e.evidence[0]?.text ?? '').replace(/\|/g, '\\|')} |`);
  }
  lines.push('', '## Errors and warnings', '', ...issueLines(issues.filter((i) => i.severity !== 'info')), '');
  lines.push('## Rules', '', ...[...new Map(issues.map((i) => [i.rule, i])).keys()].map((rule) => `- \`${rule}\``), '');
  write(join(out, 'context/platform.md'), lines.join('\n'));

  // One page per repository.
  for (const r of model.repos) {
    const entries = [...model.entries.values()].filter((e) => e.repo === r.name);
    const out1: string[] = [`# ${r.name}`, ''];
    out1.push(`${r.intent?.summary ?? r.whatItIs ?? r.description ?? ''}`.trim(), '');
    out1.push(`- Layer: ${layers.find((l) => l.id === r.layer)?.name ?? r.layer}${r.plugin ? ' (plugin)' : ''}`);
    out1.push(`- Repository: ${r.url} at ${r.commit.slice(0, 7)} (${r.date})`);
    if (r.packageName) out1.push(`- Package: ${code(r.packageName)} ${r.version ?? ''}`);
    if (r.docsUrl) out1.push(`- Docs: ${r.docsUrl}`);
    out1.push(`- Size: ${r.stats.files} files, ${r.stats.loc} lines, ${r.stats.exported} exported declarations`);
    if (r.agentFiles.length) out1.push(`- Rules for agents: ${r.agentFiles.map((f) => blob(r, f)).join(', ')}`);
    if (r.readme) out1.push('', r.readme);
    if (r.intent?.responsibilities?.length) out1.push('', '## Responsibilities', '', ...r.intent.responsibilities.map((x) => `- ${x}`));
    if (r.intent?.runtime?.length) out1.push('', '## Runtime wiring', '', ...r.intent.runtime.map((x) => `- ${x.from} → ${x.to}: ${x.note}`));
    if (entries.length) {
      out1.push('', '## Entry points');
      for (const e of entries) {
        out1.push('', `### ${code(e.name)}`, '', `Built to ${code(e.target)}${e.file ? `, from ${code(model.files.get(e.file)?.path ?? e.file)}` : ''}. ${e.api.length} exports.`, '');
        for (const item of e.api) out1.push(`- ${code(item.name)}${item.typeOnly ? ' (type)' : ''}: ${code(item.signature || item.symbolKind)}${item.symbol ? ` — ${item.symbol}` : ''}`);
      }
    }
    const deps = r.dependencies;
    if (deps.length) {
      out1.push('', '## Dependencies', '', '| Name | Spec | Kind | Family |', '| --- | --- | --- | --- |');
      for (const d of deps) out1.push(`| ${d.name} | ${d.spec} | ${d.source === 'packed.json' ? 'packed' : d.dev ? 'dev' : 'runtime'} | ${d.repo ?? (d.family ? 'yes' : 'no')} |`);
    }
    const usedBy = model.repoEdges.filter((e) => e.to === r.name);
    if (usedBy.length) out1.push('', '## Used by', '', ...usedBy.map((e) => `- ${e.from} (${e.kind}, ${e.weight})`));
    if (r.adrs.length) out1.push('', '## Decisions (ADRs)', '', ...r.adrs.map((a) => `- ${a.number} ${a.title}${a.status ? ` (${a.status})` : ''}: ${blob(r, a.path)}`));
    const files = [...model.files.values()].filter((f) => f.repo === r.name);
    if (files.length) {
      out1.push('', '## Files', '', '| File | Role | Lines | What it is |', '| --- | --- | --- | --- |');
      for (const f of files) out1.push(`| [${f.path}](${site}${mdPath.file(f)}) | ${f.role} | ${f.loc} | ${firstLine(f.doc).replace(/\|/g, '\\|')} |`);
    }
    const ri = issuesInRepo(r.name);
    if (ri.length) out1.push('', '## Issues', '', ...issueLines(ri));
    write(join(out, mdPath.repo(r.name)), out1.join('\n') + '\n');
  }

  // One page per file.
  const importers = new Map<string, { file: string; line: number; spec: string }[]>();
  for (const f of model.files.values()) {
    for (const ref of f.imports) {
      const t = ref.targetFile;
      if (t) (importers.get(t) ?? importers.set(t, []).get(t)!).push({ file: f.id, line: ref.line, spec: ref.spec });
    }
  }
  for (const f of model.files.values()) {
    const r = model.repos.find((x) => x.name === f.repo)!;
    const o: string[] = [`# ${f.repo}/${f.path}`, '', `Node id: ${code(f.id)}. ${f.role}, ${f.loc} lines. Source: ${blob(r, f.path)}`, ''];
    if (f.doc) o.push(f.doc, '');
    if (f.tested === false) o.push('No test reaches this file through imports.', '');
    if (f.imports.length) {
      o.push('## Imports', '');
      for (const ref of f.imports) o.push(`- line ${ref.line}: ${code(ref.spec)} → ${ref.targetFile ?? ref.target ?? 'unresolved'}${ref.kind !== 'import' ? ` (${ref.kind})` : ''}${ref.names.length ? `: ${ref.names.map((n) => n.imported === n.local ? n.imported : `${n.imported} as ${n.local}`).join(', ')}` : ''}`);
      o.push('');
    }
    const by = importers.get(f.id) ?? [];
    if (by.length) o.push('## Imported by', '', ...by.map((b) => `- ${b.file}:${b.line}`), '');
    if (f.symbols.length) {
      o.push('## Declarations', '');
      for (const sid of f.symbols) {
        const s = model.symbols.get(sid)!;
        o.push(`### ${s.exported ? 'export ' : ''}${s.symbolKind} ${s.name} (line ${s.line})`, '', '```ts', s.signature, '```');
        if (s.doc) o.push('', s.doc);
        if (s.members?.length) o.push('', ...s.members.map((m) => `- ${m.static ? 'static ' : ''}${code(m.signature)} (line ${m.line})`));
        if (s.usedBy.length) o.push('', `Used by: ${s.usedBy.join(', ')}`);
        o.push('');
      }
    }
    const fi = byNode.get(f.id);
    if (fi?.length) o.push('## Issues', '', ...issueLines(fi), '');
    write(join(out, mdPath.file(f)), o.join('\n'));
  }
}
